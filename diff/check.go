package diff

import (
	"fmt"
	"strings"

	"github.com/shogo82148/schemalex-deploy/format"
	"github.com/shogo82148/schemalex-deploy/model"
)

// checkChanges are the changes of the CHECK constraints of a table.
type checkChanges struct {
	drop    []*model.CheckConstraint // the constraints in the old table to drop
	add     []*model.CheckConstraint // the constraints in the new table to add
	enforce []checkPair              // the constraints whose enforcement changes
}

// checkPair is a pair of the corresponding constraints in the old and new tables.
type checkPair struct {
	from, to *model.CheckConstraint
}

// diffChecks compares the CHECK constraints of the old and new tables.
//
// The constraints are matched as follows:
//
//  1. A named constraint in the new table corresponds to the constraint with the same name in the old table.
//     The names are case-insensitive.
//  2. An unnamed constraint in the new table corresponds to a constraint with the same expression in the old table,
//     regardless of its name, because the name is generated by the server, e.g. `t_chk_1`.
//     The expressions are compared as written first, and then normalized by tableNormalizer.
//
// The matched constraints are dropped and added again if their expressions differ,
// and the enforcement is changed by ALTER CHECK if it differs.
// The constraints without the corresponding ones are dropped or added.
func (ctx *alterCtx) diffChecks() (*checkChanges, error) {
	if ctx.checks != nil {
		return ctx.checks, nil
	}

	from, to := ctx.from.Checks, ctx.to.Checks
	pairs := make([]int, len(to)) // pairs[j] is the index of the constraint in from corresponding to to[j], or -1
	matched := make([]bool, len(from))
	for j := range pairs {
		pairs[j] = -1
	}
	pair := func(i, j int) {
		pairs[j] = i
		matched[i] = true
	}

	// 1. match the named constraints by their names.
	for j, t := range to {
		if !t.Name.Valid {
			continue
		}
		for i, f := range from {
			if !matched[i] && f.Name.Valid && equalIdent(f.Name.Ident, t.Name.Ident) {
				pair(i, j)
				break
			}
		}
	}

	// 2. match the unnamed constraints by their expressions.
	// the unnamed constraints in the old table are preferred, and then the named ones.
	matchByExpr := func(fromExpr, toExpr func(int) string) {
		for _, named := range []bool{false, true} {
			for j, t := range to {
				if t.Name.Valid || pairs[j] >= 0 {
					continue
				}
				for i, f := range from {
					if !matched[i] && f.Name.Valid == named && fromExpr(i) == toExpr(j) {
						pair(i, j)
						break
					}
				}
			}
		}
	}
	matchByExpr(
		func(i int) string { return from[i].Expr },
		func(j int) string { return to[j].Expr },
	)
	if hasUnmatchedChecks(to, pairs, matched) {
		normalizedFrom, normalizedTo, err := ctx.normalizedChecks()
		if err != nil {
			return nil, err
		}
		if normalizedFrom != nil && normalizedTo != nil {
			matchByExpr(
				func(i int) string { return normalizedFrom[i].Expr },
				func(j int) string { return normalizedTo[j].Expr },
			)
		}
	}

	changes := &checkChanges{}
	for i, f := range from {
		if !matched[i] {
			changes.drop = append(changes.drop, f)
		}
	}
	for j, t := range to {
		i := pairs[j]
		if i < 0 {
			changes.add = append(changes.add, t)
			continue
		}
		f := from[i]
		equal, err := ctx.equalCheckExpr(i, j)
		if err != nil {
			return nil, err
		}
		if !equal {
			changes.drop = append(changes.drop, f)
			changes.add = append(changes.add, t)
			continue
		}
		if f.NotEnforced != t.NotEnforced {
			changes.enforce = append(changes.enforce, checkPair{from: f, to: t})
		}
	}
	ctx.checks = changes
	return changes, nil
}

// hasUnmatchedChecks reports whether both an unnamed constraint in the new table
// and a constraint in the old table are not matched yet.
func hasUnmatchedChecks(to []*model.CheckConstraint, pairs []int, matched []bool) bool {
	var unmatchedFrom, unmatchedTo bool
	for _, m := range matched {
		if !m {
			unmatchedFrom = true
			break
		}
	}
	for j, t := range to {
		if !t.Name.Valid && pairs[j] < 0 {
			unmatchedTo = true
			break
		}
	}
	return unmatchedFrom && unmatchedTo
}

// equalCheckExpr reports whether the expressions of from.Checks[i] and to.Checks[j] are equivalent.
// They are compared as written first, and then normalized by tableNormalizer.
func (ctx *alterCtx) equalCheckExpr(i, j int) (bool, error) {
	if ctx.from.Checks[i].Expr == ctx.to.Checks[j].Expr {
		return true, nil
	}
	normalizedFrom, normalizedTo, err := ctx.normalizedChecks()
	if err != nil {
		return false, err
	}
	if normalizedFrom == nil || normalizedTo == nil {
		return false, nil
	}
	return normalizedFrom[i].Expr == normalizedTo[j].Expr, nil
}

// normalizedChecks returns the constraints of the old and new tables normalized by tableNormalizer.
// The constraints are in the same order as the original ones.
// It returns nil if they cannot be normalized.
func (ctx *alterCtx) normalizedChecks() (from, to []*model.CheckConstraint, err error) {
	normalizedFrom, normalizedTo, err := ctx.normalize()
	if err != nil {
		return nil, nil, err
	}
	if normalizedFrom != nil && len(normalizedFrom.Checks) == len(ctx.from.Checks) {
		from = normalizedFrom.Checks
	}
	if normalizedTo != nil && len(normalizedTo.Checks) == len(ctx.to.Checks) {
		to = normalizedTo.Checks
	}
	return from, to, nil
}

// checkName returns the name of the constraint in the old table.
// If the constraint does not have its name, it guesses the name from the current schema.
func (ctx *alterCtx) checkName(chk *model.CheckConstraint) (model.Ident, error) {
	if chk.Name.Valid {
		return chk.Name.Ident, nil
	}
	return ctx.guessCheckName(chk)
}

// guessCheckName guesses the name of the constraint that does not have its name, from the current schema.
// It finds the constraint with the same expression in the current schema.
// The expression in the current schema is normalized by the server,
// so the expression in the old table is also compared after it is normalized by tableNormalizer.
func (ctx *alterCtx) guessCheckName(chk *model.CheckConstraint) (model.Ident, error) {
	cur := ctx.cur
	if cur == nil {
		return "", fmt.Errorf("can not find the name of the check constraint: CHECK (%s)", chk.Expr)
	}

	normalized, _, err := ctx.normalizedChecks()
	if err != nil {
		return "", err
	}
	exprs := func(i int) (raw, norm string) {
		raw = ctx.from.Checks[i].Expr
		norm = raw
		if normalized != nil {
			norm = normalized[i].Expr
		}
		return
	}

	// the constraints with the same expression are indistinguishable,
	// so the n-th one in the "from" corresponds to the n-th candidate in the current schema.
	var raw, norm string
	nth := 0
	for i, c := range ctx.from.Checks {
		if c == chk {
			raw, norm = exprs(i)
			break
		}
	}
	for i, c := range ctx.from.Checks {
		if c == chk {
			break
		}
		if r, n := exprs(i); !c.Name.Valid && (r == raw || n == norm) {
			nth++
		}
	}

LOOP:
	for _, c := range cur.Checks {
		if !c.Name.Valid || (c.Expr != raw && c.Expr != norm) {
			continue
		}

		// this name should not be used in the "from".
		for _, c2 := range ctx.from.Checks {
			if c2.Name.Valid && equalIdent(c2.Name.Ident, c.Name.Ident) {
				continue LOOP
			}
		}

		if nth > 0 {
			nth--
			continue
		}
		return c.Name.Ident, nil // found
	}
	return "", fmt.Errorf("can not find the name of the check constraint: CHECK (%s)", chk.Expr)
}

// dropTableChecks drops the CHECK constraints.
// They are dropped before the columns, because a column used by a constraint cannot be dropped.
func (ctx *alterCtx) dropTableChecks() error {
	changes, err := ctx.diffChecks()
	if err != nil {
		return err
	}
	for _, chk := range changes.drop {
		name, err := ctx.checkName(chk)
		if err != nil {
			return err
		}
		// MySQL supports DROP CHECK and DROP CONSTRAINT, but MariaDB supports only DROP CONSTRAINT.
		ctx.begin()
		ctx.writeString("DROP CONSTRAINT ")
		ctx.writeIdent(name)
	}
	return nil
}

// addTableChecks adds the CHECK constraints.
// They are added after the columns, because they may use the new columns.
func (ctx *alterCtx) addTableChecks() error {
	changes, err := ctx.diffChecks()
	if err != nil {
		return err
	}
	for _, chk := range changes.add {
		ctx.begin()
		ctx.writeString("ADD ")
		if err := format.SQL(&ctx.buf, chk); err != nil {
			return err
		}
	}
	return nil
}

// alterTableChecks changes the enforcement of the CHECK constraints.
// https://dev.mysql.com/doc/refman/26.10/en/create-table-check-constraints.html
func (ctx *alterCtx) alterTableChecks() error {
	changes, err := ctx.diffChecks()
	if err != nil {
		return err
	}
	for _, p := range changes.enforce {
		name, err := ctx.checkName(p.from)
		if err != nil {
			return err
		}
		ctx.begin()
		ctx.writeString("ALTER CHECK ")
		ctx.writeIdent(name)
		if p.to.NotEnforced {
			ctx.writeString(" NOT ENFORCED")
		} else {
			ctx.writeString(" ENFORCED")
		}
	}
	return nil
}

// equalIdent reports whether the identifiers are the same, ignoring case.
func equalIdent(a, b model.Ident) bool {
	return strings.EqualFold(string(a), string(b))
}
