// normalizeChecks normalizes the expressions of the CHECK constraints
// by removing spaces, backquotes and outermost parentheses, and lowering them.
func normalizeChecks(table *model.Table) (*model.Table, error) {
	tbl := *table
	tbl.Checks = nil
	r := strings.NewReplacer(" ", "", "`", "")
	for _, chk := range table.Checks {
		c := *chk
		c.Expr = strings.ToLower(r.Replace(c.Expr))
		tbl.Checks = append(tbl.Checks, &c)
	}
	return &tbl, nil
}

func TestDiff_CheckConstraints(t *testing.T) {
	// the current schema that SHOW CREATE TABLE of MySQL returns.
	const current = "CREATE TABLE `t` (\n" +
		"  `a` int DEFAULT NULL,\n" +
		"  `b` int DEFAULT NULL,\n" +
		"  CONSTRAINT `b_pos` CHECK ((`b` > 0)),\n" +
		"  CONSTRAINT `t_chk_1` CHECK ((`a` > 0)),\n" +
		"  CONSTRAINT `t_chk_2` CHECK ((`a` < 10)),\n" +
		"  CONSTRAINT `t_chk_3` CHECK ((`a` < `b`))\n" +
		") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;"

	// the current schema whose expressions are normalized by normalizeChecks.
	const currentNormalized = "CREATE TABLE `t` (\n" +
		"  `a` int DEFAULT NULL,\n" +
		"  `b` int DEFAULT NULL,\n" +
		"  CONSTRAINT `b_pos` CHECK ((b>0)),\n" +
		"  CONSTRAINT `t_chk_1` CHECK ((a>0)),\n" +
		"  CONSTRAINT `t_chk_2` CHECK ((a<10))\n" +
		");"

	tests := []struct {
		name       string
		before     string
		after      string
		current    string
		normalizer diff.TableNormalizer
		want       string
		wantErr    bool
	}{
		{
			name:   "no changes",
			before: "CREATE TABLE t (a INT, b INT, CHECK (a > 0), CONSTRAINT b_pos CHECK (b > 0) ENFORCED);",
			after:  "CREATE TABLE t (a INT, b INT, CHECK (a > 0), CONSTRAINT `B_POS` CHECK ((b > 0)));",
			want:   "",
		},
		{
			// the constraints in column definitions are same as the table constraints.
			name:   "column constraints",
			before: "CREATE TABLE t (a INT CHECK (a > 0), b INT CONSTRAINT b_pos CHECK (b > 0));",
			after:  "CREATE TABLE t (a INT, b INT, CHECK (a > 0), CONSTRAINT b_pos CHECK (b > 0));",
			want:   "",
		},
		{
			name:   "add a column with a column constraint",
			before: "CREATE TABLE t (a INT);",
			after:  "CREATE TABLE t (a INT, b INT CHECK (b > 0) NOT NULL);",
			want:   "ALTER TABLE `t` ADD COLUMN `b` INT (11) NOT NULL AFTER `a`, ADD CHECK (b > 0);\n",
		},
		{
			// the name of the constraint is generated by the server, so it is kept.
			name:   "remove the name",
			before: "CREATE TABLE t (a INT, CONSTRAINT c CHECK (a > 0));",
			after:  "CREATE TABLE t (a INT, CHECK (a > 0));",
			want:   "",
		},
		{
			name:    "add the name",
			before:  "CREATE TABLE t (a INT, b INT, CHECK (`a` > 0));",
			after:   "CREATE TABLE t (a INT, b INT, CONSTRAINT c CHECK (`a` > 0));",
			current: current,
			want:    "ALTER TABLE `t` DROP CONSTRAINT `t_chk_1`, ADD CONSTRAINT `c` CHECK (`a` > 0);\n",
		},
		{
			name:   "change the enforcement of a column constraint",
			before: "CREATE TABLE t (a INT CONSTRAINT c CHECK (a > 0));",
			after:  "CREATE TABLE t (a INT CONSTRAINT c CHECK (a > 0) NOT ENFORCED);",
			want:   "ALTER TABLE `t` ALTER CHECK `c` NOT ENFORCED;\n",
		},
		{
			name:   "change the expression and the enforcement",
			before: "CREATE TABLE t (a INT, CONSTRAINT c CHECK (a > 0));",
			after:  "CREATE TABLE t (a INT, CONSTRAINT c CHECK (a > 1) NOT ENFORCED);",
			want:   "ALTER TABLE `t` DROP CONSTRAINT `c`, ADD CONSTRAINT `c` CHECK (a > 1) NOT ENFORCED;\n",
		},
		{
			name:   "drop a table constraint and a column",
			before: "CREATE TABLE t (a INT, b INT, CONSTRAINT c CHECK (a < b), INDEX idx_b (b));",
			after:  "CREATE TABLE t (a INT);",
			want:   "ALTER TABLE `t` DROP CONSTRAINT `c`, DROP INDEX `idx_b`, DROP COLUMN `b`;\n",
		},
		{
			// the expressions are compared as written without the normalizer.
			name:   "imported schema without normalizer",
			before: current,
			after:  "CREATE TABLE t (a INT, b INT, CONSTRAINT b_pos CHECK (`b` > 0), CHECK (a > 0), CHECK (`a` < 10), CHECK (`a` < `b`));",
			want:   "ALTER TABLE `t` DROP CONSTRAINT `t_chk_1`, ADD CHECK (a > 0);\n",
		},
		{
			name:       "imported schema with normalizer",
			before:     current,
			after:      "CREATE TABLE t (a INT, b INT, CONSTRAINT b_pos CHECK (b > 0), CHECK (a > 0), CHECK (a < 10), CHECK (a < b));",
			normalizer: normalizeChecks,
			want:       "",
		},
		{
			name:       "named constraint with normalizer",
			before:     current,
			after:      "CREATE TABLE t (a INT, b INT, CONSTRAINT b_pos CHECK (B>0), CHECK (a > 0), CHECK (a < 10), CHECK (a < b));",
			normalizer: normalizeChecks,
			want:       "",
		},
		{
			name:       "change a named constraint with normalizer",
			before:     current,
			after:      "CREATE TABLE t (a INT, b INT, CONSTRAINT b_pos CHECK (b > 1), CHECK (a > 0), CHECK (a < 10), CHECK (a < b));",
			normalizer: normalizeChecks,
			want:       "ALTER TABLE `t` DROP CONSTRAINT `b_pos`, ADD CONSTRAINT `b_pos` CHECK (b > 1);\n",
		},
		{
			// the expressions in the current schema are normalized by the server,
			// so the name is not found without the normalizer.
			name:    "drop an anonymous constraint without normalizer",
			before:  "CREATE TABLE t (a INT, b INT, CHECK (a > 0), CHECK (a < 10));",
			after:   "CREATE TABLE t (a INT, b INT, CHECK (a < 10));",
			current: current,
			wantErr: true,
		},
		{
			name:       "drop an anonymous constraint with normalizer",
			before:     "CREATE TABLE t (a INT, b INT, CHECK (a > 0), CHECK (a < 10));",
			after:      "CREATE TABLE t (a INT, b INT, CHECK (a < 10));",
			current:    currentNormalized,
			normalizer: normalizeChecks,
			want:       "ALTER TABLE `t` DROP CONSTRAINT `t_chk_1`;\n",
		},
		{
			// b_pos is the name of the other constraint in the "from".
			name:       "do not guess the name used in the old schema",
			before:     "CREATE TABLE t (a INT, b INT, CHECK (b > 0), CONSTRAINT b_pos CHECK (b <> 0));",
			after:      "CREATE TABLE t (a INT, b INT, CONSTRAINT b_pos CHECK (b <> 0));",
			current:    currentNormalized,
			normalizer: normalizeChecks,
			wantErr:    true,
		},
		{
			name:    "drop an anonymous constraint without current schema",
			before:  "CREATE TABLE t (a INT, CHECK (a > 0));",
			after:   "CREATE TABLE t (a INT);",
			wantErr: true,
		},
		{
			name:   "cannot normalize",
			before: "CREATE TABLE t (a INT, CONSTRAINT c CHECK ((`a` > 0)));",
			after:  "CREATE TABLE t (a INT, CONSTRAINT c CHECK (a > 0));",
			normalizer: func(table *model.Table) (*model.Table, error) {
				return nil, nil
			},
			want: "ALTER TABLE `t` DROP CONSTRAINT `c`, ADD CONSTRAINT `c` CHECK (a > 0);\n",
		},
		{
			// the constraints are compared as written if the normalizer drops them.
			name:   "normalizer without constraints",
			before: "CREATE TABLE t (a INT, CONSTRAINT c CHECK ((`a` > 0)));",
			after:  "CREATE TABLE t (a INT, CONSTRAINT c CHECK (a > 0));",
			normalizer: func(table *model.Table) (*model.Table, error) {
				tbl := *table
				tbl.Checks = nil
				return &tbl, nil
			},
			want: "ALTER TABLE `t` DROP CONSTRAINT `c`, ADD CONSTRAINT `c` CHECK (a > 0);\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var opts []diff.Option
			if tt.normalizer != nil {
				opts = append(opts, diff.WithTableNormalizer(tt.normalizer))
			}
			if tt.current != "" {
				opts = append(opts, diff.WithCurrentSchema(tt.current))
			}
			var buf strings.Builder
			err := diff.Strings(&buf, tt.before, tt.after, opts...)
			if tt.wantErr {
				if err == nil {
					t.Errorf("want error, but got %q", buf.String())
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if diff := cmp.Diff(tt.want, buf.String()); diff != "" {
				t.Errorf("(-want/+got)\n%s", diff)
			}
		})
	}
}

func TestDiff_CheckConstraintsNormalizerIsCalledLazily(t *testing.T) {
	var called int
	normalizer := func(table *model.Table) (*model.Table, error) {
		called++
		return normalizeChecks(table)
	}

	// the expressions are same as written, so the normalizer is not necessary.
	var buf strings.Builder
	err := diff.Strings(&buf,
		"CREATE TABLE t (a INT, CHECK (a > 0), CONSTRAINT c CHECK (a < 10));",
		"CREATE TABLE t (a INT, CHECK (a > 0), CONSTRAINT c CHECK (a < 10) NOT ENFORCED, CONSTRAINT d CHECK (a <> 5));",
		diff.WithTableNormalizer(normalizer),
	)
	if err != nil {
		t.Fatal(err)
	}
	if called != 0 {
		t.Errorf("want the normalizer is not called, but called %d times", called)
	}
	want := "ALTER TABLE `t` ADD CONSTRAINT `d` CHECK (a <> 5), ALTER CHECK `c` NOT ENFORCED;\n"
	if diff := cmp.Diff(want, buf.String()); diff != "" {
		t.Errorf("(-want/+got)\n%s", diff)
	}

	// the normalizer is called once for each of the old and new tables.
	buf.Reset()
	err = diff.Strings(&buf,
		"CREATE TABLE t (a INT, b INT AS (a + 1), CHECK (a > 0), CONSTRAINT c CHECK (a < 10));",
		"CREATE TABLE t (a INT, b INT AS (a + 1), CHECK (a>0), CONSTRAINT c CHECK (a<10));",
		diff.WithTableNormalizer(normalizer),
	)
	if err != nil {
		t.Fatal(err)
	}
	if called != 2 {
		t.Errorf("want the normalizer is called twice, but called %d times", called)
	}
	if buf.Len() > 0 {
		t.Errorf("want no diff, but got %q", buf.String())
	}
}
