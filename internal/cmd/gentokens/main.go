// writeReservedKeywords writes the list of reserved keywords to a package
// that other packages (e.g. format) can use without importing the parser.
func writeReservedKeywords(reserved []string) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/cmd/gentokens/main.go; DO NOT EDIT.\n\n")
	buf.WriteString("// Package keywords provides the list of keywords that schemalex understands.\n")
	buf.WriteString("package keywords\n\n")
	buf.WriteString("import \"strings\"\n\n")
	buf.WriteString("// IsReserved reports whether s is a reserved keyword.\n")
	buf.WriteString("// A reserved keyword must be quoted to be used as an identifier.\n")
	buf.WriteString("func IsReserved(s string) bool {\n")
	buf.WriteString("switch strings.ToUpper(s) {\n")
	buf.WriteString("case ")
	for i, ident := range reserved {
		if i > 0 {
			buf.WriteString(",\n")
		}
		buf.WriteString(strconv.Quote(ident))
	}
	buf.WriteString(":\nreturn true\n}\nreturn false\n}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprint(os.Stderr, buf.String())
		return err
	}
	return os.WriteFile(*keywordFile, formatted, 0644)
}
